//! HTML dashboard rendering for the event router daemon.
//!
//! Generates a self-contained HTML page with inline CSS showing:
//! - Daemon status (running/stopped, PID)
//! - Registered listeners with enable/disable status
//! - Recent handler execution history
//!
//! This module is used by the daemon for its own `/events` endpoint.
//! The `on --render` builtin uses the version in `colony-exec::events`.

use colony_exec::events::{EventListener, HandlerRun};

/// Render the event router dashboard as a self-contained HTML string.
pub fn render_daemon_dashboard(
    listeners: &[EventListener],
    runs: &[HandlerRun],
    events_processed: u64,
    uptime_secs: u64,
) -> String {
    let listeners_html = render_listeners(listeners);
    let runs_html = render_runs(runs);
    let uptime = format_uptime(uptime_secs);

    format!(
        r#"<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta http-equiv="refresh" content="5">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Colony Event Router - Live</title>
<style>
{DASHBOARD_CSS}
</style>
</head>
<body>
<div class="container">
<h1>Colony Event Router</h1>
<section class="status">
<h2>Daemon</h2>
<p>
  <span class="badge running">running</span>
  Uptime: {uptime} |
  Events processed: {events_processed} |
  Listeners: {listener_count}
</p>
</section>
{listeners_html}
{runs_html}
<footer>
<p>Auto-refreshes every 5s. Generated by colony-events daemon.</p>
</footer>
</div>
</body>
</html>"#,
        listener_count = listeners.len(),
    )
}

fn render_listeners(listeners: &[EventListener]) -> String {
    if listeners.is_empty() {
        return r#"<section class="listeners">
<h2>Listeners</h2>
<p class="empty">No listeners registered.</p>
</section>"#
            .to_string();
    }

    let mut rows = String::new();
    for l in listeners {
        let short_id = &l.id[..8.min(l.id.len())];
        let cls = if l.enabled { "enabled" } else { "disabled" };
        let icon = if l.enabled { "&#x2713;" } else { "&#x2717;" };
        let once = if l.once {
            " <span class=\"badge once\">once</span>"
        } else {
            ""
        };
        let filter = if l.filter.is_empty() {
            String::new()
        } else {
            format!("<code>{}</code>", html_escape(&l.filter))
        };

        rows.push_str(&format!(
            r#"<tr class="{cls}"><td><code>{short_id}</code></td><td>{icon}</td><td><code>{pat}</code>{once}</td><td><code>{handler}</code></td><td>{ht}</td><td>{filter}</td></tr>
"#,
            pat = html_escape(&l.pattern),
            handler = html_escape(&l.handler),
            ht = l.handler_type,
        ));
    }

    format!(
        r#"<section class="listeners">
<h2>Listeners ({count})</h2>
<table>
<thead><tr><th>ID</th><th>On</th><th>Pattern</th><th>Handler</th><th>Type</th><th>Filter</th></tr></thead>
<tbody>{rows}</tbody>
</table>
</section>"#,
        count = listeners.len(),
    )
}

fn render_runs(runs: &[HandlerRun]) -> String {
    if runs.is_empty() {
        return r#"<section class="runs">
<h2>Execution History</h2>
<p class="empty">No handler executions yet.</p>
</section>"#
            .to_string();
    }

    let mut rows = String::new();
    for r in runs {
        let short = &r.listener_id[..8.min(r.listener_id.len())];
        let cls = if r.exit_code == Some(0) {
            "success"
        } else {
            "error"
        };
        let exit = r.exit_code.map_or("?".to_string(), |c| c.to_string());
        let ts = chrono::DateTime::from_timestamp(r.timestamp, 0)
            .map(|dt| dt.format("%H:%M:%S").to_string())
            .unwrap_or_else(|| "?".to_string());

        rows.push_str(&format!(
            r#"<tr class="{cls}"><td>{ts}</td><td><code>{short}</code></td><td><code>{pat}</code></td><td>exit:{exit}</td><td>{dur}ms</td></tr>
"#,
            pat = html_escape(&r.pattern),
            dur = r.duration_ms,
        ));
    }

    format!(
        r#"<section class="runs">
<h2>Execution History</h2>
<table>
<thead><tr><th>Time</th><th>Listener</th><th>Pattern</th><th>Exit</th><th>Duration</th></tr></thead>
<tbody>{rows}</tbody>
</table>
</section>"#,
    )
}

fn html_escape(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}

fn format_uptime(secs: u64) -> String {
    let hours = secs / 3600;
    let minutes = (secs % 3600) / 60;
    let s = secs % 60;
    if hours > 0 {
        format!("{hours}h {minutes}m {s}s")
    } else if minutes > 0 {
        format!("{minutes}m {s}s")
    } else {
        format!("{s}s")
    }
}

