//! TypeScript code generation from MCP tool schemas
//!
//! Generates typed TypeScript client classes from MCP server tool schemas
//! using Tera templates. Generated code is cached by schema content hash
//! and written to `~/.colony/mcp-clients/<server-name>/`.

use std::collections::HashMap;
use std::path::PathBuf;
use std::sync::Arc;

use sha2::{Digest, Sha256};
use std::fmt::Write;
use tracing::{debug, info};

use crate::connection::ToolInfo;
use crate::error::{McpError, Result};

/// Information about a tool parameter extracted from JSON Schema
#[derive(Debug, Clone, serde::Serialize)]
struct ToolParam {
    name: String,
    ts_type: String,
    required: bool,
    description: Option<String>,
}

/// Tool information prepared for template rendering
#[derive(Debug, Clone, serde::Serialize)]
struct ToolTemplateData {
    name: String,
    method_name: String,
    interface_name: String,
    description: Option<String>,
    params: Vec<ToolParam>,
}

/// TypeScript code generator for MCP tool schemas
pub struct McpCodegen {
    /// Base output directory (~/.colony/mcp-clients/)
    output_dir: PathBuf,
    /// Cache of schema hash -> generated file path
    cache: HashMap<String, PathBuf>,
}

impl McpCodegen {
    /// Create a new codegen instance
    ///
    /// Output directory defaults to `~/.colony/mcp-clients/`.
    pub fn new() -> Result<Self> {
        let output_dir = dirs::home_dir()
            .ok_or_else(|| McpError::CodegenFailed {
                server: String::new(),
                message: "could not determine home directory".to_string(),
            })?
            .join(".colony")
            .join("mcp-clients");

        Self::with_output_dir(output_dir)
    }

    /// Create a new codegen instance with a custom output directory
    pub fn with_output_dir(output_dir: PathBuf) -> Result<Self> {
        Ok(Self {
            output_dir,
            cache: HashMap::new(),
        })
    }

    /// Generate TypeScript client code for a set of tools from a server
    ///
    /// Returns the path to the generated file. If the schema hash matches
    /// a previously generated file, the cached path is returned.
    pub fn generate(&mut self, server_name: &str, tools: &[ToolInfo]) -> Result<PathBuf> {
        let schema_hash = self.compute_schema_hash(tools);

        if let Some(cached_path) = self.cache.get(&schema_hash) {
            if cached_path.exists() {
                debug!(
                    server = %server_name,
                    hash = %schema_hash,
                    "using cached generated code"
                );
                return Ok(cached_path.clone());
            }
        }

        let server_dir = self.output_dir.join(server_name);
        std::fs::create_dir_all(&server_dir)?;

        let output_path = server_dir.join("client.ts");
        let content = self.render(server_name, tools, &schema_hash)?;

        std::fs::write(&output_path, &content)?;

        info!(
            server = %server_name,
            path = %output_path.display(),
            tools = tools.len(),
            "generated TypeScript client"
        );

        self.cache.insert(schema_hash, output_path.clone());

        Ok(output_path)
    }

    /// Check if generated code exists and is current for a schema hash
    pub fn is_cached(&self, tools: &[ToolInfo]) -> bool {
        let hash = self.compute_schema_hash(tools);
        self.cache.get(&hash).is_some_and(|path| path.exists())
    }

    /// Output directory for a server
    pub fn server_output_dir(&self, server_name: &str) -> PathBuf {
        self.output_dir.join(server_name)
    }

    fn render(&self, server_name: &str, tools: &[ToolInfo], schema_hash: &str) -> Result<String> {
        let tool_data: Vec<ToolTemplateData> = tools
            .iter()
            .map(|info| self.extract_tool_data(info))
            .collect();

        let class_name = to_pascal_case(server_name);
        let timestamp = chrono_timestamp();
        let mut out = String::new();

        writeln!(out, "// Auto-generated by colony-mcp — do not edit").ok();
        writeln!(out, "// Server: {server_name}").ok();
        writeln!(out, "// Schema hash: {schema_hash}").ok();
        writeln!(out, "// Generated: {timestamp}").ok();
        writeln!(out).ok();

        for tool in &tool_data {
            let desc = tool.description.as_deref().unwrap_or("No description");
            writeln!(out, "/** {desc} */").ok();
            writeln!(out, "export interface {}Params {{", tool.interface_name).ok();
            for param in &tool.params {
                let optional = if param.required { "" } else { "?" };
                writeln!(out, "  {}{}: {};", param.name, optional, param.ts_type).ok();
            }
            writeln!(out, "}}").ok();
            writeln!(out).ok();
        }

        writeln!(out, "/** MCP client for {server_name} server */").ok();
        writeln!(out, "export class {class_name}Client {{").ok();
        writeln!(out, "  private serverName = \"{server_name}\";").ok();
        writeln!(out).ok();

        for tool in &tool_data {
            let default_desc = format!("Call tool {}", tool.name);
            let desc = tool.description.as_deref().unwrap_or(&default_desc);
            writeln!(out, "  /**").ok();
            writeln!(out, "   * {desc}").ok();
            writeln!(out, "   */").ok();
            writeln!(
                out,
                "  async {}(params: {}Params): Promise<unknown> {{",
                tool.method_name, tool.interface_name
            )
            .ok();
            writeln!(
                out,
                "    return await this.callTool(\"{}\", params);",
                tool.name
            )
            .ok();
            writeln!(out, "  }}").ok();
            writeln!(out).ok();
        }

        writeln!(out, "  private async callTool(name: string, params: Record<string, unknown>): Promise<unknown> {{").ok();
        writeln!(out, "    // Colony MCP bridge handles actual transport").ok();
        writeln!(out, "    const result = await (globalThis as any).__colony_mcp_call(this.serverName, name, params);").ok();
        writeln!(out, "    if (result.isError) {{").ok();
        writeln!(out, "      throw new Error(`MCP tool ${{name}} failed: ${{JSON.stringify(result.content)}}`);").ok();
        writeln!(out, "    }}").ok();
        writeln!(out, "    return result.content;").ok();
        writeln!(out, "  }}").ok();
        writeln!(out, "}}").ok();

        Ok(out)
    }

    fn extract_tool_data(&self, info: &ToolInfo) -> ToolTemplateData {
        let name = info.tool.name.to_string();
        let description = info.tool.description.as_ref().map(|d| d.to_string());

        let params = self.extract_params(&info.tool.input_schema);

        ToolTemplateData {
            method_name: to_camel_case(&name),
            interface_name: to_pascal_case(&name),
            name,
            description,
            params,
        }
    }

    fn extract_params(
        &self,
        schema: &Arc<serde_json::Map<String, serde_json::Value>>,
    ) -> Vec<ToolParam> {
        let properties = schema.get("properties").and_then(|v| v.as_object());

        let required_fields: Vec<String> = schema
            .get("required")
            .and_then(|v| v.as_array())
            .map(|arr| {
                arr.iter()
                    .filter_map(|v| v.as_str().map(String::from))
                    .collect()
            })
            .unwrap_or_default();

        let Some(properties) = properties else {
            return Vec::new();
        };

        properties
            .iter()
            .map(|(name, prop_schema)| {
                let ts_type = json_schema_to_ts_type(prop_schema);
                let description = prop_schema
                    .as_object()
                    .and_then(|o| o.get("description"))
                    .and_then(|v| v.as_str())
                    .map(String::from);

                ToolParam {
                    name: name.clone(),
                    ts_type,
                    required: required_fields.contains(name),
                    description,
                }
            })
            .collect()
    }

    fn compute_schema_hash(&self, tools: &[ToolInfo]) -> String {
        let mut hasher = Sha256::new();

        for tool in tools {
            hasher.update(tool.tool.name.as_bytes());
            let schema_bytes = serde_json::to_vec(&*tool.tool.input_schema).unwrap_or_default();
            hasher.update(&schema_bytes);
        }

        hex::encode(hasher.finalize())
    }
}

impl std::fmt::Debug for McpCodegen {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("McpCodegen")
            .field("output_dir", &self.output_dir)
            .field("cached_schemas", &self.cache.len())
            .finish()
    }
}

/// Convert a JSON Schema type to a TypeScript type
fn json_schema_to_ts_type(schema: &serde_json::Value) -> String {
    let Some(obj) = schema.as_object() else {
        return "unknown".to_string();
    };

    match obj.get("type").and_then(|v| v.as_str()) {
        Some("string") => "string".to_string(),
        Some("number" | "integer") => "number".to_string(),
        Some("boolean") => "boolean".to_string(),
        Some("null") => "null".to_string(),
        Some("array") => {
            let item_type = obj
                .get("items")
                .map(json_schema_to_ts_type)
                .unwrap_or_else(|| "unknown".to_string());
            format!("{item_type}[]")
        }
        Some("object") => {
            if let Some(props) = obj.get("properties").and_then(|v| v.as_object()) {
                let fields: Vec<String> = props
                    .iter()
                    .map(|(k, v)| format!("{}: {}", k, json_schema_to_ts_type(v)))
                    .collect();
                format!("{{ {} }}", fields.join("; "))
            } else {
                "Record<string, unknown>".to_string()
            }
        }
        _ => {
            if let Some(any_of) = obj.get("anyOf").and_then(|v| v.as_array()) {
                let types: Vec<String> = any_of.iter().map(json_schema_to_ts_type).collect();
                types.join(" | ")
            } else if let Some(one_of) = obj.get("oneOf").and_then(|v| v.as_array()) {
                let types: Vec<String> = one_of.iter().map(json_schema_to_ts_type).collect();
                types.join(" | ")
            } else if let Some(enum_vals) = obj.get("enum").and_then(|v| v.as_array()) {
                let variants: Vec<String> = enum_vals
                    .iter()
                    .map(|v| match v {
                        serde_json::Value::String(s) => format!("\"{}\"", s),
                        other => other.to_string(),
                    })
                    .collect();
                variants.join(" | ")
            } else {
                "unknown".to_string()
            }
        }
    }
}

/// Convert snake_case or kebab-case to PascalCase
fn to_pascal_case(s: &str) -> String {
    s.split(['_', '-', '.'])
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut chars = part.chars();
            let first = chars
                .next()
                .map(|c| c.to_uppercase().to_string())
                .unwrap_or_default();
            format!("{}{}", first, chars.as_str())
        })
        .collect()
}

/// Convert snake_case or kebab-case to camelCase
fn to_camel_case(s: &str) -> String {
    let pascal = to_pascal_case(s);
    let mut chars = pascal.chars();
    let first = chars
        .next()
        .map(|c| c.to_lowercase().to_string())
        .unwrap_or_default();
    format!("{}{}", first, chars.as_str())
}

fn chrono_timestamp() -> String {
    let now = std::time::SystemTime::now();
    let duration = now
        .duration_since(std::time::UNIX_EPOCH)
        .unwrap_or_default();
    let secs = duration.as_secs();
    format!("{secs}")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_to_pascal_case() {
        assert_eq!(to_pascal_case("my_server"), "MyServer");
        assert_eq!(to_pascal_case("read-file"), "ReadFile");
        assert_eq!(to_pascal_case("some.name"), "SomeName");
        assert_eq!(to_pascal_case("already"), "Already");
    }

    #[test]
    fn test_to_camel_case() {
        assert_eq!(to_camel_case("read_file"), "readFile");
        assert_eq!(to_camel_case("list-tools"), "listTools");
        assert_eq!(to_camel_case("get"), "get");
    }

    #[test]
    fn test_json_schema_to_ts_string() {
        let schema = serde_json::json!({"type": "string"});
        assert_eq!(json_schema_to_ts_type(&schema), "string");
    }

    #[test]
    fn test_json_schema_to_ts_number() {
        let schema = serde_json::json!({"type": "number"});
        assert_eq!(json_schema_to_ts_type(&schema), "number");

        let schema = serde_json::json!({"type": "integer"});
        assert_eq!(json_schema_to_ts_type(&schema), "number");
    }

    #[test]
    fn test_json_schema_to_ts_boolean() {
        let schema = serde_json::json!({"type": "boolean"});
        assert_eq!(json_schema_to_ts_type(&schema), "boolean");
    }

    #[test]
    fn test_json_schema_to_ts_array() {
        let schema = serde_json::json!({"type": "array", "items": {"type": "string"}});
        assert_eq!(json_schema_to_ts_type(&schema), "string[]");
    }

    #[test]
    fn test_json_schema_to_ts_object() {
        let schema = serde_json::json!({"type": "object"});
        assert_eq!(json_schema_to_ts_type(&schema), "Record<string, unknown>");
    }

    #[test]
    fn test_json_schema_to_ts_enum() {
        let schema = serde_json::json!({"enum": ["a", "b", "c"]});
        assert_eq!(json_schema_to_ts_type(&schema), "\"a\" | \"b\" | \"c\"");
    }

    #[test]
    fn test_json_schema_to_ts_any_of() {
        let schema = serde_json::json!({
            "anyOf": [{"type": "string"}, {"type": "number"}]
        });
        assert_eq!(json_schema_to_ts_type(&schema), "string | number");
    }

    #[test]
    fn test_codegen_schema_hash_deterministic() {
        let tool = rmcp::model::Tool {
            name: std::borrow::Cow::Borrowed("test_tool"),
            title: None,
            description: Some(std::borrow::Cow::Borrowed("A test tool")),
            input_schema: std::sync::Arc::new(serde_json::Map::new()),
            output_schema: None,
            annotations: None,
            execution: None,
            icons: None,
            meta: None,
        };

        let info = ToolInfo {
            tool: tool.clone(),
            server_name: "test".to_string(),
        };

        let codegen = McpCodegen::with_output_dir(PathBuf::from("/tmp/test")).unwrap();
        let hash1 = codegen.compute_schema_hash(std::slice::from_ref(&info));
        let hash2 = codegen.compute_schema_hash(&[info]);
        assert_eq!(hash1, hash2);
    }

    #[test]
    fn test_codegen_renders_template() {
        let mut schema = serde_json::Map::new();
        let mut properties = serde_json::Map::new();
        properties.insert(
            "path".to_string(),
            serde_json::json!({"type": "string", "description": "File path"}),
        );
        schema.insert("type".to_string(), serde_json::json!("object"));
        schema.insert(
            "properties".to_string(),
            serde_json::Value::Object(properties),
        );
        schema.insert("required".to_string(), serde_json::json!(["path"]));

        let tool = rmcp::model::Tool {
            name: std::borrow::Cow::Borrowed("read_file"),
            title: None,
            description: Some(std::borrow::Cow::Borrowed("Read a file from disk")),
            input_schema: std::sync::Arc::new(schema),
            output_schema: None,
            annotations: None,
            execution: None,
            icons: None,
            meta: None,
        };

        let info = ToolInfo {
            tool,
            server_name: "filesystem".to_string(),
        };

        let codegen = McpCodegen::with_output_dir(PathBuf::from("/tmp/test")).unwrap();
        let result = codegen.render("filesystem", &[info], "abc123");
        assert!(result.is_ok());

        let content = result.unwrap();
        assert!(content.contains("FilesystemClient"));
        assert!(content.contains("ReadFileParams"));
        assert!(content.contains("path: string"));
        assert!(content.contains("readFile"));
        assert!(content.contains("abc123"));
    }
}
