//! HTML dashboard rendering for the heartbeat system.
//!
//! Generates a self-contained HTML page with inline CSS showing:
//! - Current checklist from HEARTBEAT.md
//! - Run history table (reverse chronological)
//! - Live findings from the most recent run
//!
//! Auto-refreshes via `<meta http-equiv="refresh">` matching the heartbeat
//! interval. No JavaScript framework or build step required.

use super::types::{HeartbeatRun, HeartbeatStatus, Severity};

/// Render the heartbeat dashboard as a self-contained HTML string.
///
/// `checklist_content` is the raw HEARTBEAT.md body (rendered as pre-formatted text).
/// `runs` is the list of recent runs (newest first).
/// `interval_secs` is used for the auto-refresh interval.
pub fn render_dashboard(
    checklist_content: &str,
    runs: &[HeartbeatRun],
    interval_secs: u64,
    mode: &str,
) -> String {
    let checklist_html = render_checklist(checklist_content, interval_secs, mode);
    let history_html = render_history(runs);
    let findings_html = render_findings(runs.first());

    format!(
        r#"<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta http-equiv="refresh" content="{interval_secs}">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Colony Heartbeat</title>
<style>
{css}
</style>
</head>
<body>
<div class="container">
<h1>Colony Heartbeat</h1>
{checklist_html}
{history_html}
{findings_html}
<footer>
<p>Auto-refreshes every {interval_secs}s. Generated by <code>heartbeat render</code>.</p>
</footer>
</div>
</body>
</html>"#,
        css = DASHBOARD_CSS,
    )
}

/// Render the current checklist section.
fn render_checklist(content: &str, interval_secs: u64, mode: &str) -> String {
    let escaped = html_escape(content);
    format!(
        r#"<section class="checklist">
<h2>Current Checklist</h2>
<div class="meta">
  <span class="badge mode">{mode}</span>
  <span class="badge interval">every {interval_display}</span>
</div>
<pre class="checklist-body">{escaped}</pre>
</section>"#,
        interval_display = format_interval(interval_secs),
    )
}

/// Render the run history table.
fn render_history(runs: &[HeartbeatRun]) -> String {
    if runs.is_empty() {
        return r#"<section class="history">
<h2>Run History</h2>
<p class="empty">No runs recorded yet.</p>
</section>"#
            .to_string();
    }

    let mut rows = String::new();
    for run in runs {
        let status_class = status_css_class(run.status);
        let time = format_timestamp(run.timestamp);
        let duration = format!("{:.1}s", run.duration_ms as f64 / 1000.0);
        let warn_count = run
            .findings
            .iter()
            .filter(|f| f.severity == Severity::Warn)
            .count();
        let alert_count = run
            .findings
            .iter()
            .filter(|f| f.severity == Severity::Alert)
            .count();
        let findings_summary = format!("{warn_count} warn, {alert_count} alert");
        let run_id_short = if run.id.len() > 8 {
            &run.id[..8]
        } else {
            &run.id
        };

        let href = format!("#{}", run.id);
        rows.push_str(&format!(
            "<tr class=\"{status_class}\">\n\
             <td>{time}</td>\n\
             <td>{duration}</td>\n\
             <td><span class=\"status-badge {status_class}\">{status}</span></td>\n\
             <td>{findings_summary}</td>\n\
             <td><a href=\"{href}\" class=\"run-link\">{run_id_short}</a></td>\n\
             </tr>\n",
            status = run.status,
            run_id_short = run_id_short,
        ));
    }

    format!(
        r#"<section class="history">
<h2>Run History</h2>
<table>
<thead>
<tr>
  <th>Time</th>
  <th>Duration</th>
  <th>Status</th>
  <th>Findings</th>
  <th>Run ID</th>
</tr>
</thead>
<tbody>
{rows}
</tbody>
</table>
</section>"#
    )
}

/// Render the live findings from the most recent run.
fn render_findings(latest: Option<&HeartbeatRun>) -> String {
    let Some(run) = latest else {
        return String::new();
    };

    let mut findings_html = String::new();
    for finding in &run.findings {
        let severity_class = match finding.severity {
            Severity::Pass => "finding-pass",
            Severity::Warn => "finding-warn",
            Severity::Alert => "finding-alert",
        };
        let escaped_msg = html_escape(&finding.message);
        findings_html.push_str(&format!(
            r#"<div class="finding {severity_class}">
  <span class="severity">{severity}:</span> {escaped_msg}
</div>
"#,
            severity = finding.severity,
        ));
    }

    let raw_escaped = html_escape(&run.raw_output);

    format!(
        r#"<section class="findings" id="{id}">
<h2>Latest Run</h2>
<div class="findings-list">
{findings_html}
</div>
<details>
<summary>Full Agent Output</summary>
<pre class="raw-output">{raw_escaped}</pre>
</details>
</section>"#,
        id = run.id,
    )
}

/// Convert a `HeartbeatStatus` to a CSS class name.
fn status_css_class(status: HeartbeatStatus) -> &'static str {
    match status {
        HeartbeatStatus::Pass => "status-pass",
        HeartbeatStatus::Warn => "status-warn",
        HeartbeatStatus::Alert => "status-alert",
        HeartbeatStatus::Unstructured => "status-unstructured",
        HeartbeatStatus::Timeout => "status-timeout",
        HeartbeatStatus::Error => "status-error",
    }
}

/// Format a Unix timestamp as a human-readable time string.
fn format_timestamp(timestamp: i64) -> String {
    use chrono::{TimeZone, Utc};
    match Utc.timestamp_opt(timestamp, 0) {
        chrono::LocalResult::Single(dt) => dt.format("%H:%M:%S").to_string(),
        _ => "unknown".to_string(),
    }
}

/// Format an interval in seconds as a human-readable string.
fn format_interval(secs: u64) -> String {
    if secs >= 86400 {
        format!("{}d", secs / 86400)
    } else if secs >= 3600 {
        format!("{}h", secs / 3600)
    } else if secs >= 60 {
        format!("{}m", secs / 60)
    } else {
        format!("{secs}s")
    }
}

/// Basic HTML escaping for text content.
fn html_escape(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}

