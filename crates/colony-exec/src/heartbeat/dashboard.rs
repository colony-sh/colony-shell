#[cfg(test)]
mod tests {
    use super::*;
    use crate::heartbeat::types::{Finding, Severity};

    fn make_run(id: &str, status: HeartbeatStatus, findings: Vec<Finding>) -> HeartbeatRun {
        HeartbeatRun {
            id: id.to_string(),
            timestamp: 1_710_000_000,
            duration_ms: 8200,
            status,
            findings,
            raw_output: "PASS: Tests passing\nWARN: Some issue".to_string(),
            checklist_path: "/tmp/HEARTBEAT.md".to_string(),
            interval_secs: 1800,
        }
    }

    #[test]
    fn test_render_dashboard_basic() {
        let checklist = "- [ ] Check tests\n- [x] Done item\n";
        let runs = vec![make_run(
            "run-1",
            HeartbeatStatus::Pass,
            vec![Finding {
                severity: Severity::Pass,
                message: "Tests passing".to_string(),
            }],
        )];
        let html = render_dashboard(checklist, &runs, 1800, "notify");
        assert!(html.contains("<!DOCTYPE html>"));
        assert!(html.contains("Colony Heartbeat"));
        assert!(html.contains("Check tests"));
        assert!(html.contains("notify"));
        assert!(html.contains("30m"));
        assert!(html.contains("Tests passing"));
    }

    #[test]
    fn test_render_dashboard_empty_runs() {
        let html = render_dashboard("- [ ] Check tests\n", &[], 1800, "notify");
        assert!(html.contains("No runs recorded yet"));
    }

    #[test]
    fn test_render_dashboard_with_alerts() {
        let runs = vec![make_run(
            "run-alert",
            HeartbeatStatus::Alert,
            vec![
                Finding {
                    severity: Severity::Alert,
                    message: "Server down".to_string(),
                },
                Finding {
                    severity: Severity::Pass,
                    message: "Disk OK".to_string(),
                },
            ],
        )];
        let html = render_dashboard("- [ ] Check server\n", &runs, 300, "active");
        assert!(html.contains("status-alert"));
        assert!(html.contains("Server down"));
        assert!(html.contains("active"));
        assert!(html.contains("5m"));
    }

    #[test]
    fn test_html_escape() {
        assert_eq!(html_escape("<script>"), "&lt;script&gt;");
        assert_eq!(html_escape("a & b"), "a &amp; b");
        assert_eq!(html_escape("\"quoted\""), "&quot;quoted&quot;");
    }

    #[test]
    fn test_format_interval() {
        assert_eq!(format_interval(30), "30s");
        assert_eq!(format_interval(300), "5m");
        assert_eq!(format_interval(1800), "30m");
        assert_eq!(format_interval(3600), "1h");
        assert_eq!(format_interval(86400), "1d");
    }

    #[test]
    fn test_auto_refresh_interval() {
        let html = render_dashboard("- [ ] item\n", &[], 600, "notify");
        assert!(html.contains(r#"content="600""#));
    }
}
